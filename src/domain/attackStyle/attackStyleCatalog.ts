export const DEFAULT_ATTACK_STYLE_ID = 'melee';

const byId = new Map(ATTACK_STYLES.map((s) => [s.id, s]));

export function findAttackStyle(id: string): AttackStyleDefinition | null {
  return byId.get(id) ?? null;
}

export function defaultAttackStyle(): AttackStyleDefinition {
  const style = byId.get(DEFAULT_ATTACK_STYLE_ID);
  if (!style) throw new Error('default attack style missing');
  return style;
}

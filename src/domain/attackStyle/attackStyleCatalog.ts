// 攻撃スタイルカタログ(F11)。数値はすべて調整可の初期値。ID・系統・押下・長押し・コストは F11 の表と一致させる。

const NONE: CostSpec = { type: 'none' };
const stamina = (amount: number): CostSpec => ({ type: 'stamina', amount });
const energy = (amount: number): CostSpec => ({ type: 'energy', amount });
const staminaPerSec = (rate: number): CostSpec => ({ type: 'staminaPerSecond', rate });
const energyPerSec = (rate: number): CostSpec => ({ type: 'energyPerSecond', rate });

const sphere = (radius: number, forward = 1.0): HitShape => ({ type: 'sphere', radius, forward });
const fan = (radius: number, angleDeg: number): HitShape => ({ type: 'fan', radius, angleDeg });
const ring = (radius: number, width = 0.8): HitShape => ({ type: 'ring', radius, width });
const line = (length: number, width: number): HitShape => ({ type: 'line', length, width });

const stage = (
  damage: number,
  startup: number,
  active: number,
  total: number,
  advance = 0.3,
): ComboStageSpec => ({
  damage,
  startup,
  active,
  total,
  advance,
});

const MELEE_TARGET = { halfAngleDeg: 30, range: 3.0 };

function combo(
  stages: readonly ComboStageSpec[],
  opts: Partial<Omit<ComboSpec, 'kind' | 'stages'>> = {},
): ComboSpec {
  return {
    kind: 'combo',
    stages,
    shape: sphere(1.2),
    comboWindow: 0.8,
    hitClass: 'light',
    knockback: 1.7,
    energyPerHit: 5,
    target: MELEE_TARGET,
    keepMoving: false,
    airUses: 1,
    ...opts,
  };
}

function lunge(damage: number, opts: Partial<Omit<LungeSpec, 'kind' | 'damage'>> = {}): LungeSpec {
  return {
    kind: 'lunge',
    damage,
    startup: 0.1,
    active: 0.15,
    total: 0.7,
    shape: sphere(1.5),
    lungeSpeed: 9.0,
    lungeMaxTime: 0.35,
    stopDistance: 1.0,
    target: { halfAngleDeg: 45, range: 6.0 },
    knockback: 5.0,
    hitClass: 'heavy',
    energyPerHit: 10,
    hitWhileMoving: false,
    ...opts,
  };
}

function hitscan(
  damage: number,
  range: number,
  total: number,
  opts: Partial<Omit<HitscanSpec, 'kind' | 'damage' | 'range' | 'total'>> = {},
): HitscanSpec {
  return {
    kind: 'hitscan',
    damage,
    range,
    startup: 0.05,
    total,
    rays: 1,
    spreadDeg: 0,
    pierce: false,
    target: { halfAngleDeg: 15, range },
    knockback: 1.0,
    hitClass: 'light',
    energyPerHit: 3,
    airborne: true,
    beamWidth: 0,
    ...opts,
  };
}

function charge(
  maxTime: number,
  release: ActionSpec,
  scale: ChargeSpec['scale'],
  opts: Partial<Omit<ChargeSpec, 'kind' | 'maxTime' | 'release' | 'scale'>> = {},
): ChargeSpec {
  return { kind: 'charge', maxTime, moveSpeed: 1.8, release, scale, ...opts };
}

function area(
  damage: number,
  shape: HitShape,
  opts: Partial<Omit<AreaSpec, 'kind' | 'damage' | 'shape'>> = {},
): AreaSpec {
  return {
    kind: 'area',
    damage,
    shape,
    startup: 0.2,
    active: 0.1,
    total: 0.7,
    knockback: 3.0,
    hitClass: 'medium',
    energyPerHit: 5,
    movement: 'stop',
    ...opts,
  };
}

function multihit(
  damage: number,
  interval: number,
  count: number,
  opts: Partial<Omit<MultihitSpec, 'kind' | 'damage' | 'interval' | 'count'>> = {},
): MultihitSpec {
  return {
    kind: 'multihit',
    damage,
    interval,
    count,
    shape: sphere(1.2),
    moveSpeed: 0,
    hitClass: 'light',
    knockback: 0.5,
    energyPerHit: 2,
    whileHeld: false,
    maxDuration: interval * count,
    ...opts,
  };
}

function projectile(
  damage: number,
  speed: number,
  range: number,
  opts: Partial<Omit<ProjectileSpec, 'kind' | 'damage' | 'speed' | 'range'>> = {},
): ProjectileSpec {
  return {
    kind: 'projectile',
    damage,
    speed,
    range,
    count: 1,
    spreadDeg: 0,
    interval: 0,
    gravity: false,
    homing: false,
    returning: false,
    bounces: 0,
    pierce: false,
    radius: 0.25,
    hitClass: 'light',
    knockback: 1.0,
    energyPerHit: 3,
    target: { halfAngleDeg: 15, range },
    startup: 0.1,
    total: 0.4,
    airborne: true,
    ...opts,
  };
}

function placed(
  object: PlacedSpec['object'],
  opts: Partial<Omit<PlacedSpec, 'kind' | 'object'>> = {},
): PlacedSpec {
  return {
    kind: 'placed',
    object,
    lifetime: 10,
    radius: 1.5,
    damage: 30,
    interval: 0,
    delay: 0,
    maxCount: 3,
    forward: 0,
    hitClass: 'medium',
    knockback: 3.0,
    energyPerHit: 5,
    count: 1,
    spreadDeg: 0,
    ...opts,
  };
}

function summon(
  entity: SummonSpec['entity'],
  opts: Partial<Omit<SummonSpec, 'kind' | 'entity'>> = {},
): SummonSpec {
  return {
    kind: 'summon',
    entity,
    count: 1,
    lifetime: 10,
    damage: 8,
    interval: 1.5,
    range: 8,
    hitClass: 'light',
    energyPerHit: 2,
    ...opts,
  };
}

function guard(opts: Partial<Omit<GuardSpec, 'kind'>> = {}): GuardSpec {
  return {
    kind: 'guard',
    window: 0.5,
    angleDeg: 120,
    reduction: 1,
    onSuccess: 'counter',
    counterDamage: 40,
    toppleSeconds: 0,
    failRecovery: 0.5,
    staminaPerSecond: 0,
    moveSpeed: 0,
    autoRiposte: false,
    ...opts,
  };
}

function movement(
  move: MovementSpec['move'],
  requires: MovementSpec['requires'],
  opts: Partial<Omit<MovementSpec, 'kind' | 'move' | 'requires'>> = {},
): MovementSpec {
  return {
    kind: 'movement',
    move,
    requires,
    distance: 3,
    speed: 9,
    height: 0,
    invincible: 0,
    then: null,
    windowSeconds: 0.3,
    ...opts,
  };
}

